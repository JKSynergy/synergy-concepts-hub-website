#!/usr/bin/env python3
"""Prepare web-sized portfolio images from the originals in ../images/.

Run:  python build_images.py        (needs Pillow: pip install Pillow)

Reads   _review/portfolio.json
Writes  approved items  -> assets/img/work/<id>-<width>.jpg   (published)
        pending items   -> _review/preview/assets/img/work/    (local review preview only)
        _review/portfolio.images.json  (sizes, read by build.py)
        _review/ASSET_REVIEW.md        (human-readable manifest)

Rejected items and items with "proposed": false are never processed.
Images are resized only (never cropped). Metadata (EXIF, GPS) is stripped.
"""
import json, os, sys

try:
    from PIL import Image, ImageOps
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
MANIFEST = os.path.join(HERE, "_review", "portfolio.json")
SIZES_OUT = os.path.join(HERE, "_review", "portfolio.images.json")
REVIEW_MD = os.path.join(HERE, "_review", "ASSET_REVIEW.md")
PUBLIC_DIR = os.path.join(HERE, "assets", "img", "work")
PREVIEW_DIR = os.path.join(HERE, "_review", "preview", "assets", "img", "work")

WIDTHS = (640, 1280)   # grid sizes (srcset)
LARGE = 2000           # longest edge for the full-size view
QUALITY = 82
REQUIRED = ("id", "source", "category", "group", "caption", "alt", "status")


def load():
    with open(MANIFEST, encoding="utf8") as f:
        data = json.load(f)
    ids = set()
    for it in data["items"]:
        missing = [k for k in REQUIRED if not it.get(k)]
        if missing:
            sys.exit(f"{it.get('id', '?')}: missing {missing}")
        if it["id"] in ids:
            sys.exit(f"duplicate id {it['id']}")
        ids.add(it["id"])
        if it["status"] not in ("approved", "pending", "rejected"):
            sys.exit(f"{it['id']}: unknown status {it['status']}")
    return data


def flatten(im):
    im = ImageOps.exif_transpose(im)
    if im.mode in ("RGBA", "LA", "P"):
        im = im.convert("RGBA")
        bg = Image.new("RGB", im.size, (255, 255, 255))
        bg.paste(im, mask=im.split()[-1])
        return bg
    return im.convert("RGB")


def save(im, path):
    im.save(path, "JPEG", quality=QUALITY, optimize=True, progressive=True)


def process(it, out_dir):
    src = os.path.join(REPO, it["source"])
    if not os.path.exists(src):
        sys.exit(f"{it['id']}: source not found: {it['source']}")
    im = flatten(Image.open(src))
    w, h = im.size
    files = {}
    for tw in WIDTHS:
        if tw >= w and tw != WIDTHS[0]:
            continue
        r = im if tw >= w else im.resize((tw, round(h * tw / w)), Image.LANCZOS)
        name = f"{it['id']}-{r.size[0]}.jpg"
        save(r, os.path.join(out_dir, name))
        files[str(r.size[0])] = [name, r.size[0], r.size[1]]
    scale = min(1, LARGE / max(w, h))
    big = im if scale == 1 else im.resize((round(w * scale), round(h * scale)), Image.LANCZOS)
    name = f"{it['id']}-full.jpg"
    save(big, os.path.join(out_dir, name))
    files["full"] = [name, big.size[0], big.size[1]]
    return {"w": w, "h": h, "files": files}


def review_md(data):
    def cell(v):
        return (str(v) if v else "").replace("|", "/").replace("\n", " ")
    rows = []
    for it in data["items"]:
        shown = "never (not proposed)" if not it.get("proposed", True) else {
            "approved": "public site", "pending": "preview only", "rejected": "never"}[it["status"]]
        rows.append(f"| {cell(it['id'])} | {cell(it['status'])} | {shown} | {cell(it['category'])} / {cell(it['group'])} | "
                    f"{cell(it['caption'])} | {cell(it.get('client'))} | {cell(it['source'])} | {cell(it.get('attribution'))} | "
                    f"{cell(it.get('permissions'))} | {cell(it.get('identifying'))} | {cell(it.get('treatment'))} | {cell(it.get('approved_by'))} |")
    counts = {}
    for it in data["items"]:
        counts[it["status"]] = counts.get(it["status"], 0) + 1
    cases = "\n".join(f"| {c['slug']} | {c['status']} | {cell(c.get('note'))} |" for c in data.get("cases", []))
    return f"""# Portfolio asset review

Generated by `build_images.py` from `_review/portfolio.json`. Edit the JSON, not this file.

Rules: only `approved` items are published. `pending` items appear only in the local review preview
(`_review/preview/`), marked PENDING. Ownership is never inferred from a filename, watermark, EXIF data or folder.
To approve an item, record who approved it and on what basis in `approved_by`.

Totals: {', '.join(f'{k} {v}' for k, v in sorted(counts.items()))}.

| id | status | shown on | category / group | caption | client | source | attribution | permissions | identifying info | treatment | approved by |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
{chr(10).join(rows)}

## Case studies

| slug | status | note |
| --- | --- | --- |
{cases}
"""


def main():
    data = load()
    os.makedirs(PUBLIC_DIR, exist_ok=True)
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    sizes, n = {}, {"approved": 0, "pending": 0}
    for it in data["items"]:
        if it["status"] == "rejected" or not it.get("proposed", True):
            continue
        out = PUBLIC_DIR if it["status"] == "approved" else PREVIEW_DIR
        info = process(it, out)
        info["dir"] = "public" if it["status"] == "approved" else "preview"
        sizes[it["id"]] = info
        n[it["status"]] += 1
    with open(SIZES_OUT, "w", encoding="utf8") as f:
        json.dump(sizes, f, indent=1)
    with open(REVIEW_MD, "w", encoding="utf8") as f:
        f.write(review_md(data))
    # Warn about public files whose item is no longer approved (remove them by hand before deploying).
    keep = {v[0] for i in sizes.values() if i["dir"] == "public" for v in i["files"].values()}
    stale = sorted(set(os.listdir(PUBLIC_DIR)) - keep)
    print(f"images: {n['approved']} approved (public), {n['pending']} pending (preview only)")
    if stale:
        print("WARNING: files in assets/img/work/ no longer belong to an approved item. Remove before deploying:")
        for s in stale:
            print("  ", s)


if __name__ == "__main__":
    main()
